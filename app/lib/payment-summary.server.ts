/**
 * Fund-wide view powering /admin/payments. Same `PendingPaymentItem` shape so
 * the UI reuses the /thanh-toan card style.
 *
 * `outgoing` = refunds the fund still owes members (pass-slot hoan_tien rows
 * not yet marked paid). `incoming` = vãng-lai → quỹ amounts the fund still
 * needs to collect from members (vang_lai votes without a self-marked payment).
 *
 * `paid` flag toggles between pending and done views.
 */
export async function loadFundPayments(
  d1: D1Database,
  opts: { paid: boolean },
): Promise<PendingPaymentsSummary> {
  const db = getDb(d1);
  const prices = await getPrices(d1);

  // ---- Outgoing (refunds) ----
  const refunds = await db.query.refundPayments.findMany({
    where: opts.paid
      ? isNotNull(schema.refundPayments.paidAt)
      : isNull(schema.refundPayments.paidAt),
  });
  const outgoing: PendingPaymentItem[] = [];
  if (refunds.length) {
    const voteIds = refunds.map((r) => r.voteId);
    const votes = await db.query.votes.findMany({
      where: inArray(schema.votes.id, voteIds),
    });
    const voteById = new Map(votes.map((v) => [v.id, v] as const));
    const memberIds = Array.from(new Set(votes.map((v) => v.userId)));
    const sessionIds = Array.from(new Set(votes.map((v) => v.playSessionId)));
    const [members, sessions] = await Promise.all([
      memberIds.length
        ? db.query.users.findMany({ where: inArray(schema.users.id, memberIds) })
        : Promise.resolve([] as schema.User[]),
      sessionIds.length
        ? db.query.playSessions.findMany({
            where: inArray(schema.playSessions.id, sessionIds),
          })
        : Promise.resolve([] as schema.PlaySession[]),
    ]);
    const memberById = new Map(members.map((u) => [u.id, u] as const));
    const sessionById = new Map(sessions.map((s) => [s.id, s] as const));
    for (const r of refunds) {
      const vote = voteById.get(r.voteId);
      if (!vote) continue;
      const member = memberById.get(vote.userId);
      const session = sessionById.get(vote.playSessionId);
      if (!member || !session) continue;
      outgoing.push({
        id: `fund-refund-${r.voteId}`,
        direction: "out",
        kind: "pass_refund",
        amount: r.amount,
        sessionDate: session.date,
        sessionWeekday: session.weekday as WeekdayCode,
        counterpartyName: member.name,
        counterpartyPhone: member.phone,
        counterpartyQrUrl: member.qrImageKey
          ? `/qr/${encodeURIComponent(member.qrImageKey)}`
          : null,
        counterpartyMomoLink: member.momoLink ?? null,
        confirm: opts.paid ? undefined : { intent: "fund-mark-refund-paid", targetId: r.voteId },
        paidAt: opts.paid ? r.paidAt ?? undefined : undefined,
      });
    }
  }

  // ---- Incoming (vãng-lai → quỹ) ----
  const vangLaiVotes = await db.query.votes.findMany({
    where: and(
      eq(schema.votes.status, "vang_lai"),
      isNull(schema.votes.originalVoterId),
    ),
  });
  const incoming: PendingPaymentItem[] = [];
  if (vangLaiVotes.length) {
    const voteIds = vangLaiVotes.map((v) => v.id);
    const sessionIds = Array.from(new Set(vangLaiVotes.map((v) => v.playSessionId)));
    const [sessions, payments] = await Promise.all([
      db.query.playSessions.findMany({
        where: inArray(schema.playSessions.id, sessionIds),
      }),
      db.query.vangLaiPayments.findMany({
        where: inArray(schema.vangLaiPayments.voteId, voteIds),
      }),
    ]);
    const sessionById = new Map(sessions.map((s) => [s.id, s] as const));
    const monthIds = Array.from(new Set(sessions.map((s) => s.monthId)));
    const months = monthIds.length
      ? await db.query.months.findMany({
          where: inArray(schema.months.id, monthIds),
        })
      : [];
    const doneMonthIds = new Set(
      months.filter((m) => m.status === "done").map((m) => m.id),
    );
    const paidById = new Map(payments.map((p) => [p.voteId, p] as const));
    const memberIds = Array.from(new Set(vangLaiVotes.map((v) => v.userId)));
    const members = memberIds.length
      ? await db.query.users.findMany({ where: inArray(schema.users.id, memberIds) })
      : [];
    const memberById = new Map(members.map((u) => [u.id, u] as const));
    for (const v of vangLaiVotes) {
      const paid = paidById.get(v.id);
      const session = sessionById.get(v.playSessionId);
      if (!session || !doneMonthIds.has(session.monthId)) continue;
      const matchesFilter = opts.paid ? !!paid : !paid;
      if (!matchesFilter) continue;
      const member = memberById.get(v.userId);
      if (!member) continue;
      incoming.push({
        id: `fund-vl-${v.id}`,
        direction: "in",
        kind: "vang_lai_quy",
        amount: priceForVangLaiQuy(member.gender, prices),
        sessionDate: session.date,
        sessionWeekday: session.weekday as WeekdayCode,
        counterpartyName: member.name,
        counterpartyPhone: member.phone,
        counterpartyQrUrl: member.qrImageKey
          ? `/qr/${encodeURIComponent(member.qrImageKey)}`
          : null,
        counterpartyMomoLink: member.momoLink ?? null,
        paidAt: opts.paid ? paid?.paidAt ?? undefined : undefined,
      });
    }
  }

  return opts.paid
    ? {
        outgoing: outgoing.sort(byPaidAtDesc),
        incoming: incoming.sort(byPaidAtDesc),
      }
    : {
        outgoing: outgoing.sort(byDateAsc),
        incoming: incoming.sort(byDateAsc),
      };
}

/** Admin marks a refund as paid. Returns false if already paid or not found. */
export async function markRefundPaid(
  d1: D1Database,
  voteId: string,
  adminUserId: string,
): Promise<{ ok: true } | { error: string; status?: number }> {
  const db = getDb(d1);
  const row = await db.query.refundPayments.findFirst({
    where: eq(schema.refundPayments.voteId, voteId),
  });
  if (!row) return { error: "Không tìm thấy khoản hoàn tiền.", status: 404 };
  if (row.paidAt) return { error: "Đã ghi nhận trước đó.", status: 400 };
  const now = Date.now();
  await db
    .update(schema.refundPayments)
    .set({ paidAt: now, paidByUserId: adminUserId })
    .where(eq(schema.refundPayments.voteId, voteId));
  return { ok: true };
}

/**
 * Voted-vãng-lai voteIds the user has self-marked as paid. Used by both the
 * Thanh toán tab (filter "Cần chuyển") AND the trang-chu banner suppressor —
 * keeping the lookup in one place keeps the two UIs consistent without each
 * route writing its own join.
 */
export async function loadMyPaidVangLaiVoteIds(
  d1: D1Database,
  userId: string,
): Promise<string[]> {
  const db = getDb(d1);
  const myVangLai = await db.query.votes.findMany({
    where: and(eq(schema.votes.userId, userId), eq(schema.votes.status, "vang_lai")),
  });
  if (myVangLai.length === 0) return [];
  const paid = await db.query.vangLaiPayments.findMany({
    where: inArray(
      schema.vangLaiPayments.voteId,
      myVangLai.map((v) => v.id),
    ),
  });
  return paid.map((p) => p.voteId);
}

/**
 * Cheap count of outstanding outgoing payments for the homepage card and
 * (eventually) the nav badge. Avoids loading the full `PendingPaymentItem`
 * payload — just two count queries.
 */
export async function loadOutstandingCount(
  d1: D1Database,
  userId: string,
): Promise<number> {
  const db = getDb(d1);

  const pendingPass = await db.query.passRequests.findMany({
    where: and(
      eq(schema.passRequests.claimedByUserId, userId),
      isNull(schema.passRequests.confirmedAt),
    ),
  });

  const myVangLai = await db.query.votes.findMany({
    where: and(
      eq(schema.votes.userId, userId),
      eq(schema.votes.status, "vang_lai"),
      isNull(schema.votes.originalVoterId),
    ),
  });
  if (myVangLai.length === 0) return pendingPass.length;

  // Only sessions in 'done' months count — pre-done vãng lai aren't ready to pay yet.
  const sessions = await db.query.playSessions.findMany({
    where: inArray(
      schema.playSessions.id,
      myVangLai.map((v) => v.playSessionId),
    ),
  });
  const months = await db.query.months.findMany({
    where: inArray(
      schema.months.id,
      Array.from(new Set(sessions.map((s) => s.monthId))),
    ),
  });
  const doneMonthIds = new Set(months.filter((m) => m.status === "done").map((m) => m.id));
  const sessionInDone = new Map(sessions.map((s) => [s.id, doneMonthIds.has(s.monthId)] as const));
  const eligibleVangLai = myVangLai.filter((v) => sessionInDone.get(v.playSessionId));
  if (eligibleVangLai.length === 0) return pendingPass.length;

  const paid = await db.query.vangLaiPayments.findMany({
    where: inArray(
      schema.vangLaiPayments.voteId,
      eligibleVangLai.map((v) => v.id),
    ),
  });
  const paidSet = new Set(paid.map((p) => p.voteId));
  const unpaidVangLai = eligibleVangLai.filter((v) => !paidSet.has(v.id)).length;

  return pendingPass.length + unpaidVangLai;
}

/** Self-marks an approved vãng lai vote as "đã chuyển quỹ" — UI-only flag. */
export async function markVangLaiPaid(
  d1: D1Database,
  userId: string,
  voteId: string,
): Promise<{ ok: true } | { error: string; status?: number }> {
  const db = getDb(d1);
  const vote = await db.query.votes.findFirst({ where: eq(schema.votes.id, voteId) });
  if (!vote) return { error: "Không tìm thấy vote.", status: 404 };
  if (vote.userId !== userId) return { error: "Không có quyền.", status: 403 };
  if (vote.status !== "vang_lai") return { error: "Vote không phải vãng lai.", status: 400 };
  const now = Date.now();
  await db
    .insert(schema.vangLaiPayments)
    .values({ voteId, userId, paidAt: now })
    .onConflictDoUpdate({
      target: schema.vangLaiPayments.voteId,
      set: { paidAt: now },
    });
  return { ok: true };
}
